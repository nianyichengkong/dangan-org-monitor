def division_for(admin_code: str) -> tuple[str, str]:
    """返回 (市, 县区)；查不到返回空元素。"""
    code = (admin_code or "").strip()
    if code[:6] in PATCH:
        return PATCH[code[:6]]
    if code[:6] in DIV:
        return DIV[code[:6]]
    # 省本级/直属特殊段（如 110000、147000，以 0000 结尾且无县级归属）
    if code.endswith("0000") and code[:2] in PROV_NAME:
        return PROV_NAME[code[:2]], "本级"
    if code[:4] in CITY_FALLBACK:
        return CITY_FALLBACK[code[:4]], ""
    # 其余未收录段（省本级/开发区等特殊代码）兜底归省级本级
    if code[:2] in PROV_NAME:
        return PROV_NAME[code[:2]], "本级"
    return "", ""
